// Writes the share card fonts (D81) as base64 modules next to this file, from the pinned
// @fontsource packages in node_modules. Run after changing those packages' versions:
//   node src/app/api/og/fonts/generate.mjs
// Why embedded: the cards render on the Cloudflare Worker, which has no file system, and the
// bundler puts font files referenced with `new URL(..., import.meta.url)` next to the server code,
// not among the Worker's static assets. A JavaScript module works the same under next dev, next start,
// vitest and OpenNext. fonts.test.ts checks these files still match the installed packages.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "../../../../..");

export const FONT_FILES = {
  "bricolage-latin-800": "@fontsource/bricolage-grotesque/files/bricolage-grotesque-latin-800-normal.woff",
  "bricolage-latin-ext-800": "@fontsource/bricolage-grotesque/files/bricolage-grotesque-latin-ext-800-normal.woff",
  "manrope-latin-400": "@fontsource/manrope/files/manrope-latin-400-normal.woff",
  "manrope-latin-ext-400": "@fontsource/manrope/files/manrope-latin-ext-400-normal.woff",
  "manrope-latin-700": "@fontsource/manrope/files/manrope-latin-700-normal.woff",
  "manrope-latin-ext-700": "@fontsource/manrope/files/manrope-latin-ext-700-normal.woff",
  "plex-arabic-400": "@fontsource/ibm-plex-sans-arabic/files/ibm-plex-sans-arabic-arabic-400-normal.woff",
  "plex-arabic-700": "@fontsource/ibm-plex-sans-arabic/files/ibm-plex-sans-arabic-arabic-700-normal.woff",
};

export function fontBase64(file) {
  return readFileSync(join(root, "node_modules", file)).toString("base64");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [name, file] of Object.entries(FONT_FILES)) {
    const out = join(here, `${name}.ts`);
    writeFileSync(out, `// Generated by generate.mjs from node_modules/${file}. Do not edit.\nconst font = "${fontBase64(file)}";\nexport default font;\n`);
    console.log(`wrote ${out}`);
  }
}
